STRING_LITERALS = {"__رئيسي__": "__main__"}

# كلمتان متتاليتان تُترجمان إلى كلمة واحدة: «وإلا إذا» ← elif
TWO_WORD_KEYWORDS = {("وإلا", "إذا"): "elif", ("وإلا", "لو"): "elif"}

# في الترجمة العكسية تُعرض exec و eval بأسمائها العربية
_EXTRA_REVERSE = {"exec": "نفذ", "eval": "قيم"}

# ---------------------------------------------------------------------------
# التطبيع وبناء الجداول
# ---------------------------------------------------------------------------
_MARKS = re.compile("[ً-ٰٟـ]")
_LETTERS = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ى": "ي", "ة": "ه"})


def strip_marks(word):
    """يحذف الحركات والتطويل من الكلمة."""
    return _MARKS.sub("", word)


def normalize(word):
    """يطبّع الكلمة العربية للمطابقة مع القاموس."""
    return strip_marks(word).translate(_LETTERS)


def _build():
    to_python = {}
    to_arabic = {}
    for _title, table in CATEGORIES:
        for py_name, arabic_names in table.items():
            for arabic in arabic_names:
                if not arabic.isidentifier():
                    raise ValueError(f"اسم غير صالح في القاموس: {arabic!r}")
                key = normalize(arabic)
                existing = to_python.get(key)
                if existing is not None and existing != py_name:
                    raise ValueError(
                        f"تعارض في القاموس: {arabic!r} ← {existing!r} و {py_name!r}")
                to_python[key] = py_name
            to_arabic.setdefault(py_name, arabic_names[0])
    for py_name, arabic in _EXTRA_REVERSE.items():
        to_arabic.setdefault(py_name, arabic)
    return to_python, to_arabic


ARABIC_TO_PYTHON, PYTHON_TO_ARABIC = _build()

